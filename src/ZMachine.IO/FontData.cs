namespace ZMachine.IO;

/// <summary>
/// Embedded bitmap font data for vintage platform character sets.
/// Each font is stored as a byte array: one byte per scanline row
/// (MSB = leftmost pixel), glyphs covering ASCII 32–126.
/// </summary>
/// <remarks>
/// Font data is derived from the public-domain character ROM patterns
/// of each platform. Glyphs are simplified representations faithful
/// to the original pixel dimensions and style.
/// </remarks>
public static class FontData
