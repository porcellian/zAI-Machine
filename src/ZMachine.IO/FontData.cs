    /// <summary>
    /// Creates the C64 8×8 bitmap font.
    /// Commodore 64 character ROM style — uppercase PETSCII mapped to ASCII.
    /// </summary>
    public static BitmapFont CreateC64()
    {
        return new BitmapFont("C64 8×8", GenerateC64(), 8, 8);
    }

    /// <summary>
    /// Creates the Apple II 7×8 bitmap font.
    /// Apple II character generator style — 7 pixels wide (bit 7 unused),
    /// rendered in an 8-pixel-wide cell with 1 pixel right margin.
    /// </summary>
    public static BitmapFont CreateAppleII()
    {
        return new BitmapFont("Apple II 7×8", GenerateAppleII(), 7, 8);
    }

    /// <summary>
    /// Creates the IBM CGA 8×8 bitmap font.
    /// IBM PC CGA character ROM — the original PC font.
    /// </summary>
    public static BitmapFont CreateCGA()
    {
        return new BitmapFont("CGA 8×8", GenerateCGA(), 8, 8);
    }

    /// <summary>
    /// Creates the IBM EGA 8×14 bitmap font.
    /// IBM PC EGA character ROM — taller glyphs than CGA.
    /// </summary>
    public static BitmapFont CreateEGA()
    {
        return new BitmapFont("EGA 8×14", GenerateEGA(), 8, 14);
    }

    /// <summary>
    /// Creates the IBM VGA 8×16 bitmap font.
    /// Equivalent to the BuiltInFont but exposed via the BitmapFont API.
    /// </summary>
    public static BitmapFont CreateVGA()
    {
        return BitmapFont.CreateBuiltIn();
    }

    /// <summary>
    /// Creates the Amiga Topaz-style 8×8 bitmap font.
    /// Based on the Amiga Workbench Topaz font proportions.
    /// </summary>
    public static BitmapFont CreateAmiga()
    {
        return new BitmapFont("Amiga 8×8", GenerateAmiga(), 8, 8);
    }

    /// <summary>All available fonts, for enumeration in theme selection.</summary>
    public static BitmapFont[] GetAll() =>
    [
        CreateC64(),
        CreateAppleII(),
        CreateCGA(),
        CreateEGA(),
        CreateVGA(),
        CreateAmiga(),
    ];

